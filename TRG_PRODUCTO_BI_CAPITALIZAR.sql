CREATE TRIGGER before_insert_mayusculas
BEFORE INSERT ON producto
FOR EACH ROW
BEGIN
    SET NEW.NOMBRE_PRODUCTO = CONCAT(
        UCASE(LEFT(NEW.NOMBRE_PRODUCTO, 1)),
        LCASE(SUBSTRING(NEW.NOMBRE_PRODUCTO, 2))
    );

    SET NEW.MARCA_PRODUCTO = CONCAT(
        UCASE(LEFT(NEW.MARCA_PRODUCTO, 1)),
        LCASE(SUBSTRING(NEW.MARCA_PRODUCTO, 2))
    );

    SET NEW.MODELO_PRODUCTO = CONCAT(
        UCASE(LEFT(NEW.MODELO_PRODUCTO, 1)),
        LCASE(SUBSTRING(NEW.MODELO_PRODUCTO, 2))
    );

    SET NEW.COLOR_PRODUCTO = CONCAT(
        UCASE(LEFT(NEW.COLOR_PRODUCTO, 1)),
        LCASE(SUBSTRING(NEW.COLOR_PRODUCTO, 2))
    );

    SET NEW.DESCRIPCION_PRODUCTO = CONCAT(
        UCASE(LEFT(NEW.DESCRIPCION_PRODUCTO, 1)),
        LCASE(SUBSTRING(NEW.DESCRIPCION_PRODUCTO, 2))
    );
END$$

DELIMITER ;